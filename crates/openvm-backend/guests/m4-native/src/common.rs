pub fn reveal_statement(program: [u8; 32], a: u32, b: u32, output: u32) {
    let mut hasher = Sha256::new();
    hasher.update(b"zk-jam/input/v1");
    hasher.update(1u32.to_le_bytes());
    hasher.update(12u64.to_le_bytes());
    hasher.update(2u32.to_le_bytes());
    hasher.update(a.to_le_bytes());
    hasher.update(b.to_le_bytes());
    let input_commitment: [u8; 32] = hasher.finalize().into();
    let mut public_values = [0u8; 96];
    public_values[..32].copy_from_slice(&program);
    public_values[32..64].copy_from_slice(&input_commitment);
    public_values[64..68].copy_from_slice(&output.to_le_bytes());
    for (index, chunk) in public_values.chunks_exact(4).enumerate() {
        reveal_u32(u32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]), index);
    }
}
